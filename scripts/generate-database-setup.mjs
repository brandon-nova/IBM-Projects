import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "supabase/migrations");
const migrations = readdirSync(directory).filter((name) => name.endsWith(".sql")).sort();

function withoutTransaction(sql) {
  // Remove a migration's outer transaction only; keep all function bodies and
  // permission statements intact. The combined setup has one outer transaction.
  const wrapped = sql.match(/^((?:\s*--[^\n]*(?:\n|$))*)\s*begin;\s*([\s\S]*?)\s*commit;\s*$/i);
  return wrapped ? wrapped[1] + wrapped[2] + "\n" : sql;
}

const sections = migrations.map((name) =>
  `-- Source: supabase/migrations/${name}\n${withoutTransaction(readFileSync(resolve(directory, name), "utf8"))}`
);
sections.push(`-- Source: supabase/seed.sql\n${withoutTransaction(readFileSync(resolve(root, "supabase/seed.sql"), "utf8"))}`);

const header = `-- ONE-TIME SETUP: paste this entire file into Supabase SQL Editor and Run.
-- Creates the application tables, permissions, IBM signup policy, and skills.
-- For a project without the app schema. Existing Auth users are not deleted.
-- Generated by npm run db:setup-file. Edit the source migrations, not this file.

begin;

do $setup$
begin
  if pg_catalog.to_regtype('public.workspace_role') is not null
    or pg_catalog.to_regclass('public.approved_emails') is not null
    or pg_catalog.to_regclass('public.projects') is not null then
    raise exception 'Application database objects already exist. This one-time setup was not applied.'
      using hint = 'For an existing app database, apply only missing migrations. Do not delete tables or reset the database.';
  end if;
end;
$setup$;
`;

writeFileSync(resolve(root, "supabase/setup.sql"),
  `${header}\n${sections.join("\n")}\ncommit;\n\nselect 'Database setup complete' as result;\n`
);
console.log("Created supabase/setup.sql: one query for the complete initial database setup.");
