import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "supabase/migrations");
const migrations = readdirSync(directory).filter((name) => name.endsWith(".sql")).sort();

function withoutTransaction(sql) {
  // Remove a migration's outer transaction only; keep all function bodies and
  // permission statements intact. The combined setup has one outer transaction.
  const wrapped = sql.match(/^((?:\s*--[^\n]*(?:\n|$))*)\s*begin;\s*([\s\S]*?)\s*commit;\s*$/i);
  return wrapped ? wrapped[1] + wrapped[2] + "\n" : sql;
}

const sections = migrations.map((name) =>
  `-- Source: supabase/migrations/${name}\n${withoutTransaction(readFileSync(resolve(directory, name), "utf8"))}`
);
sections.push(`-- Source: supabase/seed.sql\n${withoutTransaction(readFileSync(resolve(root, "supabase/seed.sql"), "utf8"))}`);

const header = `-- ONE-TIME SETUP: paste this entire file into Supabase SQL Editor and Run.
-- Creates the application tables, permissions, IBM signup policy, and skills.
-- For a project without the app schema. Existing Auth users are not deleted.
-- Generated by npm run db:setup-file. Edit the source migrations, not this file.

begin;

do $setup$
begin
  if pg_catalog.to_regtype('public.workspace_role') is not null
    or pg_catalog.to_regclass('public.approved_emails') is not null
    or pg_catalog.to_regclass('public.projects') is not null then
    raise exception 'Application database objects already exist. This one-time setup was not applied.'
      using hint = 'For an existing app database, apply only missing migrations. Do not delete tables or reset the database.';
  end if;
end;
$setup$;
`;

writeFileSync(resolve(root, "supabase/setup.sql"),
  `${header}\n${sections.join("\n")}\ncommit;\n\nselect 'Database setup complete' as result;\n`
);
console.log("Created supabase/setup.sql: one query for the complete initial database setup.");

const upgradeNames = migrations.filter((name) => name.startsWith("20261023"));
const upgradeHeader = `-- EXISTING DATABASE UPGRADE: apply after the four 20261022 migrations.
-- Run once in Supabase SQL Editor. No tables, users, or evidence are deleted.
-- Generated by npm run db:setup-file; edit source migrations instead.
begin;
do $upgrade$ begin
  if pg_catalog.to_regclass('public.approved_emails') is null
    or not exists(select 1 from information_schema.columns where table_schema='public' and table_name='profiles' and column_name='hidden_from_people') then
    raise exception 'Apply the four 20261022 migrations first. Fresh databases use setup.sql.';
  end if;
  if pg_catalog.to_regclass('public.skill_requests') is not null
    or pg_catalog.to_regclass('public.project_links') is not null
    or pg_catalog.to_regprocedure('public.ibm_email(text)') is not null then
    raise exception 'Some updates already exist. Apply only the individual migrations still missing; do not rerun this upgrade.';
  end if;
end; $upgrade$;
`;
writeFileSync(resolve(root, "supabase/upgrade-20261023.sql"), `${upgradeHeader}\n${upgradeNames.map((name) => `-- Source: ${name}\n${withoutTransaction(readFileSync(resolve(directory,name),"utf8"))}`).join("\n")}\ncommit;\nselect 'IBM update complete' as result;\n`);
console.log("Created supabase/upgrade-20261023.sql: ordered update for existing installations.");

const assignmentFix = readFileSync(resolve(directory,"20261023000500_assignment_search.sql"),"utf8");
writeFileSync(resolve(root,"supabase/fix-assignment-search.sql"), `-- For databases that already ran the October 23 upgrade.
-- Safe to rerun. No accounts, access settings, or memberships are changed.
-- Generated by npm run db:setup-file; edit source migration 20261023000500.
begin;
do $fix$ begin
  if pg_catalog.to_regprocedure('public.assignment_candidates(uuid,text,integer,integer)') is null then
    raise exception 'Apply upgrade-20261023.sql first; it includes this fix.';
  end if;
end; $fix$;
${withoutTransaction(assignmentFix)}
commit;
select 'Assignment search updated' as result;
`);
console.log("Created supabase/fix-assignment-search.sql: correction for previously upgraded installations.");

const projectUpdateNames=migrations.filter((name) => name>="20261023000500" && name.startsWith("20261023"));
writeFileSync(resolve(root,"supabase/update-projects.sql"), `-- EXISTING OCTOBER 23 DATABASE: assignment search, native boards, admin creation.
-- Run once. Keeps existing accounts, projects, descriptions, links, and evidence.
-- Generated by npm run db:setup-file; edit the source migrations instead.
begin;
do $projects$ begin
  if pg_catalog.to_regprocedure('public.assignment_candidates(uuid,text,integer,integer)') is null then
    raise exception 'Apply upgrade-20261023.sql first; the current full upgrade includes these changes.';
  end if;
  if pg_catalog.to_regclass('public.project_tasks') is not null then
    raise exception 'Project board tables already exist. Do not rerun this update; apply only missing individual migrations.';
  end if;
end; $projects$;
${projectUpdateNames.map((name) => `-- Source: ${name}\n${withoutTransaction(readFileSync(resolve(directory,name),"utf8"))}`).join("\n")}
commit;
select 'Project tools updated' as result;
`);
console.log("Created supabase/update-projects.sql: native boards and direct admin publication for upgraded installations.");
