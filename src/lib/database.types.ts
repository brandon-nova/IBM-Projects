import type { ApprovalStatus, Role, SubmissionStatus, WorkStatus } from "./domain";

export type Profile = { user_id: string; display_name: string; bio: string; hidden_from_people: boolean; created_at: string; updated_at: string };
export type Project = {
  id: string; creator_id: string; owner_id: string | null; title: string; description: string;
  estimated_hours: number | null; visibility: "private" | "organization"; approval_status: ApprovalStatus;
  work_status: WorkStatus; completed_by: string | null; completed_at: string | null; created_at: string; updated_at: string;
  board_mode: "native" | "external"; external_board_url: string | null;
};
export type OwnerOption = { user_id: string; display_name: string };
export type TaskStatus = "todo" | "in_progress" | "done";
export type ProjectTask = { id: string; project_id: string; title: string; description: string; status: TaskStatus; position: number; assignee_id: string | null; created_by: string; updated_by: string; created_at: string; updated_at: string };
export type Skill = { id: string; name: string; active: boolean; created_at: string };
export type SkillRequest = { id: string; requester_id: string; name: string; normalized_name: string; reason: string; status: "pending" | "approved" | "rejected"; reviewed_by: string | null; reviewed_at: string | null; feedback: string; approved_skill_id: string | null; created_at: string };
export type ProjectLink = { id: string; project_id: string; label: string; url: string; created_by: string; updated_by: string; created_at: string; updated_at: string };
export type RequestEvent = { id: string; request_id: string; actor_id: string; event: string; reason: string; created_at: string };
export type Candidate = { user_id: string; display_name: string; existing_ids: string[]; learning_ids: string[]; available_hours: number | null };
export type UserSkill = { user_id: string; skill_id: string; type: "existing" | "learning" };
export type ProjectSkill = { project_id: string; skill_id: string };
export type Member = { project_id: string; user_id: string; membership_status: "active" | "inactive"; created_at: string };
export type Request = { id: string; project_id: string; user_id: string; request_type: "join" | "invitation"; status: "pending" | "accepted" | "rejected" | "canceled"; reviewed_by: string | null; invited_by: string | null; suggestion_kind: "contribution" | "training"; reason: string; last_invited_at: string | null; responded_at: string | null; canceled_by: string | null; created_at: string; updated_at: string };
export type Deliverable = { id: string; project_id: string; contributor_id: string; url: string; summary: string; outcome: string; status: SubmissionStatus; reviewed_by: string | null; reviewed_at: string | null; feedback: string; created_at: string; updated_at: string };
export type Access = { email: string; user_id: string | null; active: boolean; created_at: string; updated_at: string };
type Table<T> = { Row: T; Insert: Partial<T>; Update: Partial<T>; Relationships: [] };
type ProjectInput = { p_title: string; p_description: string; p_skills: string[]; p_estimated_hours: number | null };
type Rpc<A, R = string> = { Args: A; Returns: R };
export type Database = {
  public: {
    Tables: {
      profiles: Table<Profile>; projects: Table<Project>; skills: Table<Skill>; user_skills: Table<UserSkill>;
      project_skills: Table<ProjectSkill>; project_members: Table<Member>; project_requests: Table<Request>;
      project_deliverables: Table<Deliverable>; approved_emails: Table<Access>;
      project_links: Table<ProjectLink>; skill_requests: Table<SkillRequest>; project_request_events: Table<RequestEvent>;
      project_tasks: Table<ProjectTask>;
      user_roles: Table<{ user_id: string; role: Role; updated_at: string }>;
      user_availability: Table<{ user_id: string; available_hours: number | null; updated_at: string }>;
    };
    Views: Record<string, never>;
    Functions: {
      save_profile_skills: Rpc<{ p_display_name: string; p_bio: string; p_existing_ids: string[]; p_learning_ids: string[]; p_available_hours: number | null }>;
      save_learning_interest: Rpc<{ p_skill_id: string }>;
      create_project_with_skills: Rpc<Omit<ProjectInput,"p_skills"> & { p_skill_ids: string[] }>;
      create_published_project: Rpc<Omit<ProjectInput,"p_skills"> & { p_skill_ids: string[]; p_owner_id?: string | null }>;
      admin_project_owners: Rpc<{ p_offset?: number; p_limit?: number }, OwnerOption[]>;
      save_project_task: Rpc<{ p_project_id: string; p_title: string; p_description: string; p_assignee_id: string | null; p_task_id?: string | null }>;
      move_project_task: Rpc<{ p_project_id: string; p_task_id: string; p_status: TaskStatus }>;
      delete_project_task: Rpc<{ p_project_id: string; p_task_id: string }>;
      set_project_board: Rpc<{ p_project_id: string; p_mode: "native" | "external"; p_url: string | null }>;
      edit_project_with_skills: Rpc<Omit<ProjectInput,"p_skills"> & { p_project_id: string; p_skill_ids: string[] }>;
      request_skill: Rpc<{ p_name: string; p_reason: string }>;
      review_skill_request: Rpc<{ p_request_id: string; p_approve: boolean; p_feedback: string }>;
      set_skill_active: Rpc<{ p_skill_id: string; p_active: boolean }>;
      save_project_link: Rpc<{ p_project_id: string; p_label: string; p_url: string; p_link_id?: string }>;
      delete_project_link: Rpc<{ p_link_id: string }>;
      invite_project_members: Rpc<{ p_project_id: string; p_user_ids: string[]; p_kind: "contribution" | "training"; p_reason: string; p_reinvite: boolean }>;
      respond_project_invitation: Rpc<{ p_request_id: string; p_accept: boolean }>;
      cancel_project_invitation: Rpc<{ p_request_id: string }>;
      remove_project_member: Rpc<{ p_project_id: string; p_user_id: string }>;
      pending_project_suggestions: Rpc<Record<string, never>, string[]>;
      assignment_candidates: Rpc<{ p_project_id: string; p_query?: string; p_offset?: number; p_limit?: number }, Candidate[]>;
      workspace_active: Rpc<Record<string, never>, boolean>;
      workspace_admin: Rpc<Record<string, never>, boolean>;
      project_visible: Rpc<{ p_project_id: string }, boolean>;
      project_member: Rpc<{ p_project_id: string }, boolean>;
      save_profile: Rpc<{ p_display_name: string; p_bio: string; p_existing_skills: string[]; p_learning_skills: string[]; p_available_hours: number | null }>;
      set_directory_visibility: Rpc<{ p_hidden: boolean }>;
      save_interest: Rpc<{ p_interest: string }>;
      create_project: Rpc<ProjectInput>;
      edit_project: Rpc<ProjectInput & { p_project_id: string }>;
      request_publication: Rpc<{ p_project_id: string }>;
      assign_owner: Rpc<{ p_project_id: string; p_owner_id: string }>;
      review_publication: Rpc<{ p_project_id: string; p_approve: boolean }>;
      request_join: Rpc<{ p_project_id: string }>;
      review_join: Rpc<{ p_request_id: string; p_accept: boolean }>;
      submit_deliverable: Rpc<{ p_project_id: string; p_url: string; p_summary: string; p_outcome: string }>;
      review_deliverable: Rpc<{ p_deliverable_id: string; p_accept: boolean; p_feedback: string }>;
      complete_project: Rpc<{ p_project_id: string }>;
      start_project: Rpc<{ p_project_id: string }>;
      manage_access: Rpc<{ p_email: string; p_active: boolean }, string | null>;
      set_user_role: Rpc<{ p_user_id: string; p_role: Role }>;
    };
    Enums: { workspace_role: Role; skill_type: "existing" | "learning"; project_visibility: "private" | "organization"; approval_status: ApprovalStatus; work_status: WorkStatus; deliverable_status: SubmissionStatus };
    CompositeTypes: Record<string, never>;
  };
};
