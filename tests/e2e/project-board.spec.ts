import {test,expect,type Page} from "@playwright/test";
import {fixtures,type Actor} from "../support";

async function login(page:Page,actor:Actor) {
  await page.goto("/login");
  await page.getByLabel("Email",{exact:true}).fill(actor.email);
  await page.getByLabel("Password",{exact:true}).fill(actor.password);
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page).toHaveURL(/\/$/);
}
test("admin publishes with an owner; native tasks survive external-board switching",async({browser}) => {
  test.setTimeout(180000);
  const f=await fixtures();
  const contexts=await Promise.all([browser.newContext(),browser.newContext({viewport:{width:390,height:844}})]);
  try {
    const admin=await f.actor("board-ui-admin",true),owner=await f.actor("board-ui-owner"),employee=await f.actor("board-ui-employee");
    const [adminPage,ownerPage]=await Promise.all(contexts.map((c) => c.newPage()));
    await login(adminPage,admin);await login(ownerPage,owner);
    await adminPage.goto("/projects/new");
    const ownerField=adminPage.getByRole("combobox",{name:"Project owner for new project",exact:true});
    const ownerValue=adminPage.locator('input[type="hidden"][name="owner_id"]');
    await expect(ownerField).toHaveValue(admin.name);
    await expect(ownerValue).toHaveValue(admin.id);
    await ownerField.fill("no-such-person-"+f.runId);
    await expect(adminPage.getByText("No people found.",{exact:true})).toBeVisible();
    await ownerField.press("Escape");
    await expect(ownerField).toHaveValue(admin.name);
    await expect(ownerValue).toHaveValue(admin.id);
    await ownerField.fill(owner.name);
    await ownerField.press("Tab");
    await expect(ownerField).toHaveValue(admin.name);
    await expect(ownerValue).toHaveValue(admin.id);
    const title=`Useful board ${f.runId}`;
    await adminPage.getByLabel("Project title",{exact:true}).fill(title);
    await adminPage.getByLabel("Description",{exact:true}).fill("a".repeat(301));
    await expect(adminPage.getByRole("button",{name:"Create and publish project",exact:true})).toBeDisabled();
    await adminPage.getByLabel("Description",{exact:true}).fill("Create a useful synthetic artifact with clear instructions.");
    await adminPage.getByRole("combobox",{name:/Skills needed/}).fill("Python");
    await adminPage.getByRole("option",{name:"Python",exact:true}).click();
    await adminPage.getByLabel("Estimated hours per week",{exact:false}).fill("4");
    await ownerField.fill(owner.name);
    await expect(adminPage.getByRole("option",{name:owner.name,exact:true})).toBeVisible();
    await ownerField.press("ArrowDown");
    await ownerField.press("Enter");
    await expect(ownerField).toHaveValue(owner.name);
    await expect(ownerValue).toHaveValue(owner.id);
    await expect(ownerField).toHaveAttribute("aria-expanded","false");
    await adminPage.getByRole("button",{name:"Create and publish project",exact:true}).click();
    await expect(adminPage).toHaveURL(/\/projects\/[0-9a-f-]+$/);
    const path=new URL(adminPage.url()).pathname,project=path.split("/").at(-1)!;
    const rows=await f.ok<{visibility:string;approval_status:string;owner_id:string}[]>(`/rest/v1/projects?id=eq.${project}`,"GET",undefined,employee.token);
    expect(rows[0]).toMatchObject({visibility:"organization",approval_status:"approved",owner_id:owner.id});
    await ownerPage.goto(path);
    const board=ownerPage.getByRole("region",{name:"Task board columns",exact:true});
    for(const column of ["To Do","In Progress","Done"]) await expect(board.getByRole("heading",{name:column,exact:true})).toBeVisible();
    await ownerPage.locator(".board-add > summary").click();
    const add=ownerPage.locator(".board-add");
    await add.getByLabel("Task title",{exact:true}).fill("Write setup instructions");
    await add.getByLabel("Task description",{exact:false}).fill("Use fictional inputs.");
    await add.getByLabel("Assign to",{exact:true}).selectOption(owner.id);
    await add.getByRole("button",{name:"Add task",exact:true}).click();
    const card=board.locator(".kanban-task").filter({has:ownerPage.getByRole("heading",{name:"Write setup instructions",exact:true})});
    await expect(card).toBeVisible();
    await card.getByLabel("Move Write setup instructions to",{exact:true}).selectOption("in_progress");
    await card.getByRole("button",{name:"Move",exact:true}).click();
    await expect(board.locator(".kanban-column").filter({has:ownerPage.getByRole("heading",{name:"In Progress",exact:true})}).getByRole("heading",{name:"Write setup instructions",exact:true})).toBeVisible();
    await ownerPage.reload();await expect(card).toBeVisible();
    expect(await ownerPage.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    const settings=ownerPage.locator(".board-settings");
    await settings.locator("summary").click();
    await settings.getByLabel("Project board",{exact:true}).selectOption("external");
    await settings.getByLabel("External board URL",{exact:true}).fill("https://example.com/fictional-board");
    await settings.getByRole("button",{name:"Save board",exact:true}).click();
    await expect(ownerPage.getByRole("link",{name:"Open board",exact:true})).toHaveAttribute("href","https://example.com/fictional-board");
    await expect(board).toHaveCount(0);
    await settings.locator("summary").click();
    await settings.getByLabel("Project board",{exact:true}).selectOption("native");
    await settings.getByRole("button",{name:"Save board",exact:true}).click();
    await expect(card).toBeVisible();
    const tasks=await f.ok<{status:string}[]>(`/rest/v1/project_tasks?project_id=eq.${project}`,"GET",undefined,owner.token);
    expect(tasks).toHaveLength(1);expect(tasks[0].status).toBe("in_progress");
  } finally {await Promise.all(contexts.map((c) => c.close()));await f.cleanup();}
});
